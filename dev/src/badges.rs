/// shields.io path text: `-` doubles, a space is `_`, and these encode.
fn esc(text: &str) -> String {
    text.replace('-', "--")
        .replace('%', "%25")
        .replace('+', "%2B")
        .replace('/', "%2F")
        .replace(' ', "_")
}

/// The block, markers included.
#[must_use]
pub(crate) fn render(f: &Facts) -> String {
    let values = f.cargo.values().into_iter().chain(f.gate());
    let filled = values.fold(TEMPLATE.to_owned(), |text, (name, value)| {
        text.replace(&format!("{{{name}|url}}"), &esc(&value))
            .replace(&format!("{{{name}}}"), &value)
    });
    filled.replace("{platforms}\n", &platforms(&f.platforms))
}

impl Cargo {
    /// The template's Cargo.toml facts, by name.
    fn values(&self) -> [(&'static str, String); 6] {
        [
            ("name", self.name.clone()),
            ("slug", self.slug.clone()),
            ("license", self.license.clone()),
            ("edition", self.edition.clone()),
            ("msrv", self.msrv.clone()),
            ("deps", self.dependencies.to_string()),
        ]
    }
}

impl Facts {
    /// The template's gate, spec and nix facts, by name.
    fn gate(&self) -> [(&'static str, String); 6] {
        let (n, (inv, bugs, nodes)) = (&self.nixpkgs, self.spec);
        let steps = format!("{} commit / {} push", self.steps.0, self.steps.1);
        [
            ("steps", steps),
            ("floor", self.floor.clone()),
            ("inv", inv.to_string()),
            ("bugs", bugs.to_string()),
            ("nodes", nodes.to_string()),
            ("nixpkgs", format!("{} ({} - {})", n.series, n.day, n.rev)),
        ]
    }
}

/// One badge per platform CI builds on, then the blank line before the
/// credits.
fn platforms(list: &[Platform]) -> String {
    let mut out: String = list
        .iter()
        .map(|(arch, os)| {
            format!(
                "[![{arch} {os}](https://img.shields.io/badge/{os}-5277C3?logo={arch}&logoColor=white)](.github/workflows/ci.yml)\n"
            )
        })
        .collect();
    out.push('\n');
    out
}

/// Replace the three generated numbers while preserving all surrounding prose.
#[must_use]
pub(crate) fn render_prose_numbers(disclaimer: &str, f: &Facts) -> String {
    let (inv, bugs, _) = f.spec;
    let text = replace_bold_number(disclaimer, "invariants", inv);
    let text = replace_bold_number(&text, "bugs", bugs);
    replace_number_after(&text, "floor of ", "%", &f.floor)
}

fn replace_bold_number(text: &str, label: &str, value: usize) -> String {
    let suffix = format!(" {label}**");
    let Some(end) = text.find(&suffix) else {
        return text.to_owned();
    };
    let Some(start) = text[..end].rfind("**") else {
        return text.to_owned();
    };
    format!("{}**{}{}", &text[..start], value, &text[end..])
}

fn replace_number_after(
    text: &str,
    prefix: &str,
    suffix: &str,
    value: &str,
) -> String {
    let Some(start) =
        text.find(prefix).and_then(|i| i.checked_add(prefix.len()))
    else {
        return text.to_owned();
    };
    let Some(number_end) = numeric_end(text, start) else {
        return text.to_owned();
    };
    if number_end == start || !text[number_end..].starts_with(suffix) {
        return text.to_owned();
    }
    format!("{}{}{}", &text[..start], value, &text[number_end..])
}

fn numeric_end(text: &str, start: usize) -> Option<usize> {
    let length = text[start..]
        .bytes()
        .take_while(|byte| byte.is_ascii_digit() || *byte == b'.')
        .count();
    start.checked_add(length).filter(|end| *end > start)
}

