//! The README badge block, and the numbers `docs/LLM-DISCLAIMER.md` quotes
//! in prose. One set of facts renders both, so a badge's alt text, its URL
//! and a sentence cannot disagree. Ported from pklith-dev, MIT, same
//! author.

use crate::facts::{Nixpkgs, Platform};

/// What Cargo.toml owns.
#[derive(Debug)]
pub(crate) struct Cargo {
    /// The crate's `name`, as crates.io and docs.rs know it.
    pub(crate) name: String,
    /// `owner/repo`, from `repository`.
    pub(crate) slug: String,
    /// `license`.
    pub(crate) license: String,
    /// `edition`.
    pub(crate) edition: String,
    /// `rust-version`, the minimum supported Rust.
    pub(crate) msrv: String,
    /// Entries in `[dependencies]`; zero is a true count.
    pub(crate) dependencies: usize,
}

/// Everything the badges say, each read from the file that owns it.
#[derive(Debug)]
pub(crate) struct Facts {
    /// The Cargo.toml facts.
    pub(crate) cargo: Cargo,
    /// `.coverage`'s floor, as a percentage without trailing zeros.
    pub(crate) floor: String,
    /// Steps in hk.pkl's pre-commit and pre-push hooks.
    pub(crate) steps: (usize, usize),
    /// `V` rows, `B` rows and `SPEC.md` files across the federation.
    pub(crate) spec: (usize, usize, usize),
    /// The locked nixpkgs.
    pub(crate) nixpkgs: Nixpkgs,
    /// What CI's matrix builds on.
    pub(crate) platforms: Vec<Platform>,
}

impl Facts {
    /// Refuse a fact that reads empty or zero: a badge is not worth a
    /// guessed number. The dependency count is exempt: zero is what
    /// actlith has.
    ///
    /// # Errors
    ///
    /// The first fact that is empty or zero, named.
    pub(crate) fn checked(self) -> Result<Self, String> {
        let empty = self.empty().into_iter().find(|(_, is)| *is);
        empty.map_or(Ok(self), |(what, _)| {
            Err(format!("{what} read empty or zero; fix the source"))
        })
    }

    /// Each fact by its source, and whether it reads empty or zero.
    fn empty(&self) -> [(&'static str, bool); 8] {
        let c = &self.cargo;
        [
            ("Cargo.toml name", c.name.is_empty()),
            ("Cargo.toml repository", c.slug.is_empty()),
            ("Cargo.toml license", c.license.is_empty()),
            ("Cargo.toml edition", c.edition.is_empty()),
            ("Cargo.toml rust-version", c.msrv.is_empty()),
            ("hk.pkl steps", self.steps.0 == 0 || self.steps.1 == 0),
            ("SPEC.md rows", self.spec.0 == 0 || self.spec.2 == 0),
            ("ci.yml platforms", self.platforms.is_empty()),
        ]
    }
}

