/// What a script run left behind: exit code, recorded calls, output.
struct Ran {
    code: Option<i32>,
    log: String,
    stdout: String,
    stderr: String,
}

fn bash() -> io::Result<PathBuf> {
    let path = std::env::var_os("PATH").unwrap_or_default();
    std::env::split_paths(&path)
        .map(|dir| dir.join("bash"))
        .find(|file| file.is_file())
        .ok_or_else(|| io::Error::other("no bash on PATH"))
}

/// A fresh directory holding every seeded script at its published path.
fn scratch(name: &str) -> io::Result<PathBuf> {
    let id = std::process::id();
    let dir = std::env::temp_dir().join(format!("actlith-script-{id}-{name}"));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(dir.join("bin"))?;
    if name == "up-renamed-nodes" {
        fs::write(dir.join("flake.lock"), RENAMED_LOCK)?;
    }
    for (path, bytes) in scripts() {
        let file = dir.join(path);
        if let Some(parent) = file.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(file, bytes)?;
    }
    Ok(dir)
}

fn stubs(dir: &Path, bash: &Path) -> io::Result<()> {
    let text = format!("#!{}\n{STUB}", bash.display());
    for tool in TOOLS {
        let file = dir.join("bin").join(tool);
        fs::write(&file, &text)?;
        fs::set_permissions(&file, fs::Permissions::from_mode(0o755))?;
    }
    Ok(())
}

fn search_path(dir: &Path) -> io::Result<std::ffi::OsString> {
    let path = std::env::var_os("PATH").unwrap_or_default();
    let rest = std::env::split_paths(&path);
    std::env::join_paths(std::iter::once(dir.join("bin")).chain(rest))
        .map_err(io::Error::other)
}

/// `bash` without the hook's git environment (`GIT_ENV`).
fn bare(bash: &Path) -> Command {
    let mut cmd = Command::new(bash);
    for var in GIT_ENV {
        cmd.env_remove(var);
    }
    cmd
}

/// Run `scripts/actlith/<script>` with `args` and extra `env`.
fn run(
    name: &str,
    script: &str,
    args: &[&str],
    env: &[(&str, &str)],
) -> io::Result<Ran> {
    let (dir, bash) = (scratch(name)?, bash()?);
    stubs(&dir, &bash)?;
    let log = dir.join("calls.log");
    fs::write(&log, "")?;
    let out = bare(&bash)
        .arg(format!("scripts/actlith/{script}"))
        .args(args)
        .current_dir(&dir)
        .env("PATH", search_path(&dir)?)
        .env("STUB_LOG", &log)
        .envs(env.iter().copied())
        .output()?;
    ran(&out, &log)
}

fn ran(out: &Output, log: &Path) -> io::Result<Ran> {
    let stdout = String::from_utf8_lossy(&out.stdout).into_owned();
    let stderr = String::from_utf8_lossy(&out.stderr).into_owned();
    let log = fs::read_to_string(log)?;
    Ok(Ran {
        code: out.status.code(),
        log,
        stdout,
        stderr,
    })
}

fn calls(ran: &Ran) -> Vec<&str> {
    ran.log.lines().collect()
}

fn update_pins(name: &str, args: &[&str], env: &[(&str, &str)]) -> Ran {
    let revs = [("STUB_REV_BEFORE", BEFORE), ("STUB_REV_AFTER", AFTER)];
    let env: Vec<_> = revs.iter().chain(env).copied().collect();
    run(name, "update-pins.sh", args, &env).unwrap_or(Ran {
        code: None,
        log: String::new(),
        stdout: String::new(),
        stderr: String::new(),
    })
}

